export function getMockResponse(endpoint) {

  const albumMatch = endpoint.match(/\/albums\/([a-zA-Z0-9_]+)$/);
  if (albumMatch) {
    const id = albumMatch[1];
    if (MOCK_ALBUMS[id]) {
      return MOCK_ALBUMS[id];
    }

    for (const list of Object.values(MOCK_GENRE_ALBUMS)) {
      const found = list.find((a) => a.id === id);
      if (found) return found;
    }

    return UN_VERANO_SIN_TI;
  }

  if (endpoint.startsWith('/albums?ids=')) {
    return {
      albums: [UN_VERANO_SIN_TI, LOVER, AFTER_HOURS, HIT_ME_HARD, MOTOMAMI, RADICAL_OPTIMISM],
    };
  }

  const artistMatch = endpoint.match(/\/artists\/([a-zA-Z0-9_]+)$/);
  if (artistMatch) {
    const id = artistMatch[1];
    if (MOCK_ARTISTS[id]) {
      return MOCK_ARTISTS[id];
    }
    return MOCK_ARTISTS['06HL4z0CvFAxyc27GXpf02'];
  }

  if (endpoint.startsWith('/artists?ids=')) {
    return {
      artists: Object.values(MOCK_ARTISTS),
    };
  }

  if (endpoint.includes('/albums?include_groups=')) {
    return {
      items: [UN_VERANO_SIN_TI, LOVER, AFTER_HOURS, HIT_ME_HARD, MOTOMAMI, RADICAL_OPTIMISM],
    };
  }

  if (endpoint.startsWith('/search?')) {
    const urlParams = new URLSearchParams(endpoint.replace('/search?', ''));
    const q = (urlParams.get('q') || '').toLowerCase();

    if (q.startsWith('artist:')) {
      const artistQuery = q.replace('artist:', '').replace(/"/g, '').trim();
      const matchedArtistAlbum = Object.values(MOCK_ALBUMS).find((a) =>
        a.artists.some((art) => art.name.toLowerCase().includes(artistQuery))
      ) || UN_VERANO_SIN_TI;

      return {
        tracks: {
          items: matchedArtistAlbum.tracks.items.map((t) => ({
            ...t,
            album: {
              id: matchedArtistAlbum.id,
              name: matchedArtistAlbum.name,
              images: matchedArtistAlbum.images,
            },
          })),
        },
      };
    }

    if (q.includes('rock')) {
      return { albums: { items: MOCK_GENRE_ALBUMS.rock }, tracks: { items: [] }, artists: { items: [] } };
    }
    if (q.includes('reggaeton') || q.includes('latino') || q.includes('urban')) {
      return { albums: { items: MOCK_GENRE_ALBUMS.urban }, tracks: { items: [] }, artists: { items: [] } };
    }
    if (q.includes('chill') || q.includes('lofi') || q.includes('relax')) {
      return { albums: { items: MOCK_GENRE_ALBUMS.chill }, tracks: { items: [] }, artists: { items: [] } };
    }
    if (q.includes('electronic') || q.includes('dance') || q.includes('edm')) {
      return { albums: { items: MOCK_GENRE_ALBUMS.electronic }, tracks: { items: [] }, artists: { items: [] } };
    }

    const featuredList = [UN_VERANO_SIN_TI, LOVER, AFTER_HOURS, HIT_ME_HARD, MOTOMAMI, RADICAL_OPTIMISM];

    const allTracks = [];
    featuredList.forEach((album) => {
      album.tracks.items.forEach((t) => {
        allTracks.push({
          ...t,
          album: {
            id: album.id,
            name: album.name,
            images: album.images,
          },
        });
      });
    });

    const filteredTracks = allTracks.filter(
      (t) => t.name.toLowerCase().includes(q) || t.artists.some((a) => a.name.toLowerCase().includes(q))
    );

    const filteredAlbums = featuredList.filter(
      (a) => a.name.toLowerCase().includes(q) || a.artists.some((art) => art.name.toLowerCase().includes(q))
    );

    const filteredArtists = Object.values(MOCK_ARTISTS).filter(
      (art) => art.name.toLowerCase().includes(q)
    );

    return {
      tracks: {
        items: filteredTracks.length > 0 ? filteredTracks.slice(0, 10) : allTracks.slice(0, 10),
      },
      albums: {
        items: filteredAlbums.length > 0 ? filteredAlbums.slice(0, 6) : featuredList.slice(0, 6),
      },
      artists: {
        items: filteredArtists.length > 0 ? filteredArtists.slice(0, 6) : Object.values(MOCK_ARTISTS).slice(0, 6),
      },
    };
  }

  return null;
}
